func TestShutdownLetsActiveRequestFinish(t *testing.T) {
	listener := &closeNotifier{Listener: listen(t), closed: make(chan struct{})}
	ctx, cancel := context.WithCancel(context.Background())
	t.Cleanup(cancel)
	s := New(testConfig(), quietLogger(), func(context.Context) error { return nil })
	started := make(chan context.Context, 1)
	release := make(chan struct{})
	var releaseOnce sync.Once
	releaseHandler := func() { releaseOnce.Do(func() { close(release) }) }
	t.Cleanup(releaseHandler)
	s.Router().GET("/slow", func(c *gin.Context) {
		started <- c.Request.Context()
		<-release
		c.JSON(http.StatusOK, gin.H{"status": "finished"})
	})
	done := make(chan error, 1)
	go func() { done <- s.serve(ctx, listener) }()
	requestDone := getAsync(listener.Addr().String() + "/slow")
	requestCtx := receive(t, started)
	cancel()
	receive(t, listener.closed)
	if err := requestCtx.Err(); err != nil {
		t.Fatalf("active request was cancelled before the shutdown deadline: %v", err)
	}
	releaseHandler()
	result := receive(t, requestDone)
	if result.err != nil || result.status != http.StatusOK || result.body != `{"status":"finished"}` {
		t.Fatalf("active request did not finish: %+v", result)
	}
	if err := receive(t, done); err != nil {
		t.Fatalf("graceful shutdown: %v", err)
	}
}

func TestShutdownDeadlineClosesAndCancelsActiveRequest(t *testing.T) {
	listener := listen(t)
	ctx, cancel := context.WithCancel(context.Background())
	t.Cleanup(cancel)
	cfg := testConfig()
	cfg.ShutdownTimeout = 10 * time.Millisecond
	s := New(cfg, quietLogger(), func(context.Context) error { return nil })
	started := make(chan struct{})
	cancelled := make(chan struct{})
	s.Router().GET("/blocked", func(c *gin.Context) {
		close(started)
		<-c.Request.Context().Done()
		close(cancelled)
	})
	done := make(chan error, 1)
	go func() { done <- s.serve(ctx, listener) }()
	requestDone := getAsync(listener.Addr().String() + "/blocked")
	receive(t, started)
	cancel()
	if err := receive(t, done); !errors.Is(err, context.DeadlineExceeded) {
		t.Fatalf("shutdown error = %v, want deadline exceeded", err)
	}
	receive(t, cancelled)
	receive(t, requestDone)
}

